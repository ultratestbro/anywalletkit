// Reads Symbiosis' host chain and writes src/pools.ts — the pinned pool index tables and the pinned
// synthetic-token map the verifier binds a route to. Read-only: eth_call against the host chain.
//
//   node scripts/build-pins.mjs            rewrite src/pools.ts
//   node scripts/build-pins.mjs --check    compare the chain with the committed file, exit 1 on drift
//
// Sources: the pool addresses are Symbiosis' published omni-pool list (USD, ETH, BTC, WBNB); every
// index → token row is the pool's own `indexToAsset(i)`; every synthetic token → (chain, real token)
// row is the host-chain Fabric's `getRealRepresentation(synth)` confirmed in the other direction with
// `getSyntRepresentation(real, chainId)`; the Fabric and the MetaRouter are read from the pinned Synthesis.
import {readFileSync, writeFileSync} from "node:fs";
import {fileURLToPath} from "node:url";
import {getAddress, toFunctionSelector} from "viem";

const HOST_RPC = process.env.SYMBIOSIS_HOST_RPC ?? "https://symbiosis.calderachain.xyz/http";
const SYNTHESIS = "0x45CFd6FB7999328F189aaD2739Fba4Be6C45E5bf";
const POOLS = {
  USD: "0xC3255E317481B95A3e61844c274dE8BAF8eDF397",
  ETH: "0x2d877Fe148dBCB056Bf71ED5232E8d580195c0f1",
  BTC: "0xBf084Ee3E5C73129167167Bd5DB9FE8513d8F7e0",
  WBNB: "0x095B362957B3E3638AE1eb7A957f392cD3Dc3c7C",
};
const CHAINS = [1, 56, 43114, 137, 42161, 10, 8453, 728126428, 85918];

let id = 0;
async function call(to, data) {
  for (let attempt = 0; ; attempt++) {
    try {
      const r = await fetch(HOST_RPC, {method: "POST", headers: {"content-type": "application/json"}, body: JSON.stringify({jsonrpc: "2.0", id: ++id, method: "eth_call", params: [{to, data}, "latest"]})});
      const j = await r.json();
      if (j.error) return null;
      return j.result;
    } catch (e) {
      if (attempt >= 4) throw e;
      await new Promise((ok) => setTimeout(ok, 500 * (attempt + 1)));
    }
  }
}
const word = (v) => BigInt(v).toString(16).padStart(64, "0");
const sel = (s) => toFunctionSelector(s);
const addr = (hex) => getAddress(`0x${hex.slice(-40)}`);

const fabric = addr(await call(SYNTHESIS, sel("fabric()")));
const metaRouter = addr(await call(SYNTHESIS, sel("metaRouter()")));

const pools = {};
const synths = {};
for (const [name, pool] of Object.entries(POOLS)) {
  const last = Number(BigInt(await call(pool, sel("lastIndex()"))));
  const rows = [];
  for (let i = 0; i < last; i++) {
    const r = await call(pool, sel("indexToAsset(uint256)") + word(i));
    let row = null;
    if (r && r.length === 2 + 64 * 7) {
      const w = r.slice(2).match(/.{64}/g);
      const token = addr(w[5]);
      const active = BigInt(`0x${w[6]}`) === 1n;
      if (active && BigInt(token) !== 0n) {
        const real = await call(fabric, sel("getRealRepresentation(address)") + word(token));
        const realAddress = real ? addr(real) : null;
        if (realAddress && BigInt(realAddress) !== 0n) {
          let chain = null;
          for (const c of CHAINS) {
            const back = await call(fabric, sel("getSyntRepresentation(address,uint256)") + word(realAddress) + word(c));
            if (back && addr(back) === token) { if (chain !== null) throw new Error(`${token} maps back from two chains`); chain = c; }
          }
          if (chain !== null) {
            const decimals = Number(BigInt(await call(token, sel("decimals()"))));
            synths[token] = {chain, real: realAddress, decimals};
            row = token;
          }
        }
      }
    }
    rows.push(row);
  }
  while (rows.length && rows[rows.length - 1] === null) rows.pop();
  pools[name] = {address: getAddress(pool), rows};
}

const lines = [];
lines.push("// GENERATED by scripts/build-pins.mjs from Symbiosis' host chain — do not edit by hand.");
lines.push("// `node scripts/build-pins.mjs --check` compares it with the chain; `scripts/verify-live.mjs` runs that check too.");
lines.push("");
lines.push("/** The host chain's MetaRouter (`Synthesis.metaRouter()`): the only address a host-chain pool route may hand its output to. */");
lines.push(`export const SYMBIOSIS_HOST_META_ROUTER = "${metaRouter}";`);
lines.push("/** The host chain's synthetic-token Fabric (`Synthesis.fabric()`): where the map below was read from. */");
lines.push(`export const SYMBIOSIS_HOST_FABRIC = "${fabric}";`);
lines.push("");
lines.push("/** A synthetic token of the host chain: the chain (Symbiosis' id) and the real token it stands for, and its decimals. */");
lines.push("export interface SymbiosisSynth { readonly chain: number; readonly real: string; readonly decimals: number }");
lines.push("");
lines.push("/**");
lines.push(" * Every synthetic token a served route may move — `Fabric.getRealRepresentation(synth)` confirmed with");
lines.push(" * `Fabric.getSyntRepresentation(real, chain)`. Keys are lowercase. A TON jetton's real representation is the");
lines.push(" * last 20 bytes of its master's account hash.");
lines.push(" */");
lines.push("export const SYMBIOSIS_SYNTHS: Readonly<Record<string, SymbiosisSynth>> = Object.freeze({");
for (const [t, s] of Object.entries(synths).sort((a, b) => a[1].chain - b[1].chain || a[0].localeCompare(b[0]))) {
  lines.push(`  "${t.toLowerCase()}": {chain: ${s.chain}, real: "${s.real.toLowerCase()}", decimals: ${s.decimals}},`);
}
lines.push("});");
lines.push("");
lines.push("/**");
lines.push(" * Symbiosis' host-chain pools a served route may swap in, each with its token at every index");
lines.push(" * (`pool.indexToAsset(i)`; null = an inactive index or a token of a chain this module does not serve).");
lines.push(" * Keys are lowercase pool addresses; tokens are lowercase.");
lines.push(" */");
lines.push("export const SYMBIOSIS_POOLS: Readonly<Record<string, readonly (string | null)[]>> = Object.freeze({");
for (const [name, p] of Object.entries(pools)) {
  lines.push(`  // ${name} pool`);
  lines.push(`  "${p.address.toLowerCase()}": [`);
  p.rows.forEach((t, i) => lines.push(`    ${t ? `"${t.toLowerCase()}"` : "null"}, // ${i}`));
  lines.push("  ],");
}
lines.push("});");
lines.push("");
const text = lines.join("\n");
const file = fileURLToPath(new URL("../src/pools.ts", import.meta.url));
if (process.argv.includes("--check")) {
  const now = readFileSync(file, "utf8");
  if (now !== text) { console.error("src/pools.ts differs from the host chain — review the change, then regenerate"); process.exit(1); }
  console.log(`src/pools.ts matches the host chain (${Object.keys(synths).length} synthetic tokens, ${Object.keys(pools).length} pools)`);
} else {
  writeFileSync(file, text);
  console.log(`wrote ${file}: ${Object.keys(synths).length} synthetic tokens, ${Object.keys(pools).length} pools`);
}
